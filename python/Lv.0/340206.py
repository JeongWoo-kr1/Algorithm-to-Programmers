# [PCCE 기출문제] 2번 / 각도 합치기

angle1 = int(input())
angle2 = int(input())

sum_angle = angle1 + angle2
print(sum_angle if 0>=sum_angle<=360 else sum_angle%360)

'''
풀이 : 
1. sum_angle 값을 if 문을 이용해 0과360 사이인지 체크 후 그렇지 않다면 %360을 할 생각이었습니다만 
정답을 맞추고 보니 sum_angle%360을 해도 통과됐을 것 같습니다. (머쓱)
삼항 연산자를 사용하여 해결해야한다는 강박에 사로잡힌 듯 합니다.
'''

